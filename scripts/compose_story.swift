import AppKit
import ImageIO

let args = CommandLine.arguments
guard args.count == 7 else {
    fatalError("usage: compose_story.swift <background> <logo> <output> <headline> <body> <tip>")
}

let backgroundURL = URL(fileURLWithPath: args[1])
let logoURL = URL(fileURLWithPath: args[2])
let outputURL = URL(fileURLWithPath: args[3])
let headline = args[4].replacingOccurrences(of: "|", with: "\n")
let body = args[5].replacingOccurrences(of: "|", with: "\n")
let tip = args[6].replacingOccurrences(of: "|", with: "\n")

guard let background = NSImage(contentsOf: backgroundURL),
      let logo = NSImage(contentsOf: logoURL) else {
    fatalError("could not load background or official logo")
}

let canvasSize = NSSize(width: 1080, height: 1920)
let canvas = NSImage(size: canvasSize)
canvas.lockFocus()
NSGraphicsContext.current?.imageInterpolation = .high

func color(_ hex: UInt32, alpha: CGFloat = 1) -> NSColor {
    NSColor(red: CGFloat((hex >> 16) & 0xff) / 255, green: CGFloat((hex >> 8) & 0xff) / 255, blue: CGFloat(hex & 0xff) / 255, alpha: alpha)
}

let navy = color(0x101B36)
let blue = color(0x075BFF)
let lightBlue = color(0x55B8FF)

func font(_ size: CGFloat, weight: NSFont.Weight) -> NSFont {
    NSFont(name: "Avenir Next", size: size) ?? NSFont.systemFont(ofSize: size, weight: weight)
}

func drawText(_ text: String, top: CGFloat, x: CGFloat, width: CGFloat, height: CGFloat, size: CGFloat, foreground: NSColor, weight: NSFont.Weight = .regular, alignment: NSTextAlignment = .left) {
    let paragraph = NSMutableParagraphStyle()
    paragraph.alignment = alignment
    paragraph.lineBreakMode = .byWordWrapping
    paragraph.lineSpacing = size * 0.08
    let attrs: [NSAttributedString.Key: Any] = [.font: font(size, weight: weight), .foregroundColor: foreground, .paragraphStyle: paragraph]
    NSAttributedString(string: text, attributes: attrs).draw(in: NSRect(x: x, y: canvasSize.height - top - height, width: width, height: height))
}

background.draw(in: NSRect(origin: .zero, size: canvasSize), from: .zero, operation: .copy, fraction: 1)

// Quiet white reading zone; no dark footer is introduced.
NSColor.white.withAlphaComponent(0.90).setFill()
NSBezierPath(roundedRect: NSRect(x: 56, y: canvasSize.height - 610, width: 968, height: 470), xRadius: 34, yRadius: 34).fill()

drawText(headline, top: 205, x: 84, width: 900, height: 180, size: 64, foreground: blue, weight: .bold)
drawText(body, top: 420, x: 84, width: 900, height: 120, size: 32, foreground: navy)
drawText(tip, top: 1280, x: 84, width: 900, height: 100, size: 30, foreground: navy, weight: .semibold)

// Deterministic Teslinha swoosh; it is never generated by ImageGen.
let swoosh = NSBezierPath()
swoosh.move(to: NSPoint(x: 34, y: 280))
swoosh.curve(to: NSPoint(x: 720, y: 84), controlPoint1: NSPoint(x: 70, y: 40), controlPoint2: NSPoint(x: 520, y: 42))
swoosh.lineWidth = 18
blue.setStroke()
swoosh.stroke()

let swooshHighlight = NSBezierPath()
swooshHighlight.move(to: NSPoint(x: 45, y: 304))
swooshHighlight.curve(to: NSPoint(x: 730, y: 108), controlPoint1: NSPoint(x: 100, y: 58), controlPoint2: NSPoint(x: 540, y: 58))
swooshHighlight.lineWidth = 6
lightBlue.setStroke()
swooshHighlight.stroke()

// Apply the official logo as an image, never as generated text.
logo.draw(in: NSRect(x: 72, y: 78, width: 250, height: 250), from: .zero, operation: .sourceOver, fraction: 1)

canvas.unlockFocus()
guard let rep = NSBitmapImageRep(data: canvas.tiffRepresentation!), let png = rep.representation(using: .png, properties: [:]) else {
    fatalError("could not encode output")
}
try png.write(to: outputURL)
